// PATIENT RECORD
// Central model used everywhere in the app.
// condition is derived from predictions.overallTier — never set manually.
// ─────────────────────────────────────────────────────────────────────────────
class PatientRecord {
  const PatientRecord({
    required this.rank,
    required this.name,
    required this.id,
    required this.roomNumber,
    required this.predictions,
    required this.features,
    this.primaryDoctor,
    this.issue,
    this.vitals,
    this.age,
    this.gender,
    this.diagnosis,
    this.daysAdmitted,
  });

  final int rank;
  final String name;
  final String id;
  final String roomNumber;
  final PatientPredictions predictions;
  final PatientFeatures features;
  final String? primaryDoctor;
  final String? issue;
  final String? vitals;
  final int? age;
  final String? gender;
  final String? diagnosis;
  final int? daysAdmitted;

  // Convenience getters — so existing widgets don't need updating
  double get icuRisk => predictions.icuTransferRisk;
  double get readmissionRisk => predictions.readmissionRisk;
  String get condition => predictions.overallTier;
  List<ShapValue> get shapValues => predictions.shapTransfer;

  PatientRecord copyWithRank(int newRank) => PatientRecord(
        rank: newRank,
        name: name,
        id: id,
        roomNumber: roomNumber,
        predictions: predictions,
        features: features,
        primaryDoctor: primaryDoctor,
        issue: issue,
        vitals: vitals,
        age: age,
        gender: gender,
        diagnosis: diagnosis,
        daysAdmitted: daysAdmitted,
      );
}

